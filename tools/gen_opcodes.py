"""Regenerate crates/proto/src/opcodes.rs from the AAEmu 10.x C# offsets.

Usage: python gen_opcodes.py <AAEmu checkout> [opcodes.rs]
Names the existing table uses but the C# offsets lack keep 0xfff (never sent) and are printed."""
import re, sys
from pathlib import Path
SRC = Path(sys.argv[1]) / 'AAEmu.Game' / 'Core' / 'Packets'
CS = SRC / 'C2G' / 'CSOffsets.cs'
SC = SRC / 'G2C' / 'SCOffsets.cs'
PP = SRC / 'Proxy' / 'PPOffsets.cs'
OLD = sys.argv[2] if len(sys.argv) > 2 else str(Path(__file__).resolve().parents[1] / 'crates/proto/src/opcodes.rs')
pat = re.compile(r'^\s*public const ushort (\w+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*;', re.M)
def parse(path):
    out = {}
    for m in pat.finditer(open(path, encoding='utf-8-sig').read()):
        out.setdefault(m.group(1), int(m.group(2), 0))
    return out
old = open(OLD, encoding='utf-8').read()
def old_names(mod):
    body = re.search(r'pub mod %s \{(.*?)pub const NAMES' % mod, old, re.S).group(1)
    return re.findall(r'pub const (\w+): u16', body)
def module(mod, doc, new, olds):
    lines = [f'/// `{doc}` (10.0.2.13)', f'pub mod {mod} {{']
    missing = [n for n in olds if n not in new]
    for n, v in new.items():
        lines.append(f'    pub const {n}: u16 = 0x{v:03x};')
    for n in missing:
        lines.append(f'    /// Not in the 10.x offsets (1.2 only or renamed).')
        lines.append(f'    pub const {n}: u16 = 0xfff;')
    lines.append('')
    lines.append('    /// `(opcode, name)` pairs, for logging.')
    lines.append('    pub const NAMES: &[(u16, &str)] = &[')
    for n, v in new.items():
        lines.append(f'        (0x{v:03x}, "{n}"),')
    lines.append('    ];')
    lines.append('}')
    return '\n'.join(lines), missing
tail = old[old.index('/// `GLOffsets`'):] if '/// `GLOffsets`' in old else old[old.index('pub mod gl'):]
parts, report = [], {}
for mod, doc, path in [('cs','CSOffsets',CS),('sc','SCOffsets',SC),('pp','PPOffsets',PP)]:
    text, miss = module(mod, doc, parse(path), old_names(mod)); parts.append(text); report[mod] = miss
head = ('// Generated by tools/gen_opcodes.py from the AAEmu 10.x C# offsets\n'
        '// (CSOffsets.cs, SCOffsets.cs, PPOffsets.cs). gl/lg kept from the 1.2 table (server-internal).\n'
        '#![allow(non_upper_case_globals, dead_code)]\n\n')
open(OLD, 'w', encoding='utf-8', newline='\n').write(head + '\n\n'.join(parts) + '\n\n' + tail)
for k, v in report.items():
    print(k, len(v), 'missing:', ' '.join(v))
